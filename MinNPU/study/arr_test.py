text = "abc"

# 좌측 정렬 (<): 총 7자리 중 왼쪽에 배치, 나머지는 공백
print(f"|{text:<7}|")  # 출력: |abc    |

# 우측 정렬 (>): 총 7자리 중 오른쪽에 배치, 나머지는 공백
print(f"|{text:>7}|")  # 출력: |    abc|

# 중앙 정렬 (^): 총 7자리 중 가운데 배치, 나머지는 공백
print(f"|{text:^7}|")  # 출력: |  abc  |

# 공백 대신 특정 문자(예: *)로 채우기
print(f"|{text:*<7}|") # 출력: |abc****|